#!/usr/bin/env python3
"""Generate the human review briefing from the committed evidence.

The briefing is a derived artifact: it is written from the same data the worksheets
are built from, so it cannot describe a review task the worksheets do not contain.
It carries no timestamps, so CI can verify that regeneration is a no-op.
"""
from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
OUTPUT = ROOT.parents[1] / "docs" / "three-ages-review-briefing.md"

FACADE_STYLES = ["baroque", "classical french", "renaissance-inspired", "mixed", "other", "uncertain", "not assessable"]


def read_json(name: str) -> dict:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def read_csv(name: str) -> list[dict[str, str]]:
    with (DATA / name).open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def shorten(text: str, limit: int = 320) -> str:
    text = " ".join((text or "").split())
    if len(text) <= limit:
        return text
    return text[: limit - 1].rstrip() + "…"


def main() -> None:
    units = read_json("facade-units.json")
    cases = read_json("three-ages-image-cases.json")["cases"]
    candidates = read_csv("facade-style-candidates.csv")
    register_rows = read_csv("three-ages-register-review.csv")
    structural_rows = read_csv("three-ages-structural-review.csv")
    buildings = {str(record["id"]): record for record in read_json("grand-place-buildings.json")["records"]}

    images_by_unit: dict[str, list[dict[str, str]]] = defaultdict(list)
    for case in cases:
        images_by_unit[case["facade_unit_id"]].append(case)
    register_by_source = {row["source_id"]: row for row in register_rows}
    structural_sources = {row["source_id"] for row in structural_rows}

    shared_units = [unit for unit in units["units"] if len(unit["records"]) > 1]
    gated = [row for row in register_rows if row["identity_gate"] not in {"not applicable"}]
    conflict_notes = [
        (case["source_id"], case["asset_id"], case["source_observation"])
        for case in cases
        if "disagrees" in case["source_observation"]
    ]
    recorded_conflicts = units.get("known_conflicts", [])

    lines: list[str] = []
    add = lines.append
    add("# Three Ages — review briefing")
    add("")
    add(
        "Generated by `prototypes/three-ages/generate_review_briefing.py` from the committed evidence. "
        "Do not edit by hand; the worksheets are the source of truth. Review decisions are recorded in the "
        "worksheets via `review.html` — see the [review packet](three-ages-review-packet.md) for the full "
        "procedure and controlled values."
    )
    add("")
    add("## Scope")
    add("")
    add(f"- **{len(cases)} images** across **{units['unit_count']} facade units** ({units['record_count']} City records).")
    add(f"- **{len(register_rows)} register claims** and **{len(structural_sources)} structural comparisons** (curated pilot only).")
    add("- A *facade unit* is what a style observation applies to. A City record is not a unit.")
    add("")

    if gated or shared_units or conflict_notes or recorded_conflicts:
        add("## Read this first")
        add("")
    if gated:
        add("### Identity gate — unresolved")
        add("")
        for row in gated:
            add(
                f"- **Source {row['source_id']}** ({row['name']}, {row['address']}) is gated as `{row['identity_gate']}`. "
                "Its images cannot be reviewed until you resolve the gate in the register worksheet's `identity_gate` "
                "column, and a resolved gate is refused unless you record the basis in `identity_gate_note`. "
                "The exporter refuses to record image reviews for it until then."
            )
        add("")
    if shared_units:
        add("### Shared facades — review once, as a unit")
        add("")
        for unit in shared_units:
            records = ", ".join(unit["records"])
            add(f"- **{unit['label']}** (`{unit['unit_id']}`, records {records})")
            add(f"  - {unit['note']}")
        add("")
    if conflict_notes or recorded_conflicts:
        add("### Source identity conflicts — record, do not resolve silently")
        add("")
        for conflict in recorded_conflicts:
            records = ", ".join(conflict["records"])
            monument = f", monument {conflict['monument_id']}" if conflict.get("monument_id") else ""
            add(f"- **{conflict['address']}** (record {records}{monument}): City name \"{conflict['city_name']}\", Commons name \"{conflict['commons_name']}\".")
            add(f"  - {conflict['note']}")
        seen: set[tuple[str, str]] = set()
        recorded_records = {record for conflict in recorded_conflicts for record in conflict["records"]}
        for source_id, asset_id, observation in conflict_notes:
            # A conflict already recorded in facade-units.json is listed above; do not repeat it.
            if source_id in recorded_records:
                continue
            key = (source_id, observation)
            if key in seen:
                continue
            seen.add(key)
            add(f"- **{source_id}** ({buildings[source_id]['name']}) via `{asset_id}`: {shorten(observation, 400)}")
        add("")

    add("## What to record for each image")
    add("")
    add("- `facade_style` — one controlled value: " + ", ".join(f"`{style}`" for style in FACADE_STYLES) + ".")
    add("  Choose what you perceive in the image. The `source_style_text` column is source text, not a visual label.")
    add("- `facade_observation` — visible, source-grounded features. Do not infer a construction date from style.")
    add("- `reviewer`, `reviewed_at`, `confidence` (`low` / `medium` / `high`).")
    add("")

    add("## Review queue by unit")
    add("")
    for unit in units["units"]:
        unit_id = unit["unit_id"]
        images = sorted(images_by_unit.get(unit_id, []), key=lambda case: (case["epoch"], case["asset_id"]))
        records = unit["records"]
        sharing = unit["facade_sharing"]
        add(f"### {unit['label']}")
        add("")
        add(f"`{unit_id}` · records {', '.join(records)} · {', '.join(unit['addresses'])} · {sharing}")
        add("")
        if len(records) > 1:
            add(f"> Shared facade: {unit['note']}")
            add("")
        # Several records can share one facade and their texts differ only in the house
        # emblem sentence, so no text repeats. records[0] showed "no facade of its own" for
        # the Dukes block, which describes one house, not the composition. The longest text
        # is the shared composition description; per-house emblems are additions to it.
        texts = [buildings[record_id].get("facade") or "" for record_id in records]
        texts = [text for text in texts if text.strip()]
        facade_text = shorten(max(texts, key=len)) if texts else ""
        if facade_text:
            add(f"Source facade text: {facade_text}")
            add("")
        if not images:
            add("No reviewable image for this unit.")
            add("")
            continue
        add(f"{len(images)} image(s):")
        add("")
        add("| epoch | asset | licence | credit |")
        add("| --- | --- | --- | --- |")
        for case in images:
            add(f"| {case['epoch']} | `{case['asset_id']}` | {case['licence']} | {case['credit']} |")
        add("")
        extra: list[str] = []
        for record_id in records:
            register_row = register_by_source.get(record_id)
            if register_row:
                extra.append(
                    f"register claim {record_id} (`{register_row['reported_value']}`, {register_row['claim_status']})"
                )
            if record_id in structural_sources:
                extra.append(f"structural comparison {record_id}")
        if extra:
            add("Also in the curated pilot for this unit: " + "; ".join(extra) + ".")
            add("")

    reviewable = len(cases)
    add("## Progress")
    add("")
    add(f"- Images reviewed: 0 of {reviewable} (the exporter compiles completed rows only).")
    add(f"- Register decisions: 0 of {len(register_rows)}.")
    add(f"- Structural comparisons: 0 of {len(structural_sources)}.")
    add("- An independent second review is required for at least one subset, with disagreements recorded.")
    add("")
    add("Counts above are derived at generation time and always start at zero; use the workbench's own")
    add("progress counters for live state.")
    add("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT.parents[1])} ({len(lines)} lines, {len(cases)} images, {units['unit_count']} units)")


if __name__ == "__main__":
    main()
